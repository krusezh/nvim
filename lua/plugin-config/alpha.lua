-- Set the footer
local function footer()
    -- NOTE: requires the `fortune` command (install with `brew install fortune`).
    -- Remove this function and the assignment below if the command is unavailable.
    local handle = io.popen("fortune")
    local fortune = handle:read("*a")
    handle:close()
    return (fortune:gsub("%s+$", ""))
end
dashboard.section.footer.val = footer()

-- Set the layout
